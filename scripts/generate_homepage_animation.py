"""Package the generated mascot into a looping, illustrative knowledge-flow GIF.

Requires Pillow. Run from any directory: python scripts/generate_homepage_animation.py
The mascot artwork is generated by ImageGen; this script only lays out and animates
the supplied artwork with a procedural diagram. It does not redraw the mascot.
"""

from pathlib import Path
import math

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "site" / "assets"
WIDTH, HEIGHT = 1000, 430
BG = (15, 22, 40)
CYAN = (134, 239, 223)
LAVENDER = (185, 164, 255)


def font(size, bold=False):
    candidates = [
        Path("C:/Windows/Fonts/msyhbd.ttc" if bold else "C:/Windows/Fonts/msyh.ttc"),
        Path("/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"),
        Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
    ]
    for path in candidates:
        if path.exists():
            return ImageFont.truetype(str(path), size)
    raise RuntimeError("Install a CJK font and add its path to font() for Chinese labels.")


FONTS = {size: font(size) for size in (10, 11, 12, 13, 14, 16, 20, 28)}
TITLE = font(28, bold=True)
mascot = Image.open(ASSETS / "owl-mascot.png").convert("RGBA")
mascot.thumbnail((265, 265), Image.Resampling.LANCZOS)

STEPS = [("文档导入", "解析 · 分块"), ("知识索引", "向量 · 关键词"), ("混合检索", "关联 · 融合"), ("智能回答", "推理 · 引用")]
DETAILS = [
    ("01 / 把知识带进来", "从团队文档出发，解析内容并准备索引。"),
    ("02 / 为知识建立连接", "结合向量、关键词与知识图谱组织线索。"),
    ("03 / 为问题找到依据", "多路召回相关片段，为智能体补充上下文。"),
    ("04 / 让答案有迹可循", "结合上下文生成回答，并呈现参考来源。"),
]


def frame_at(frame):
    image = Image.new("RGB", (WIDTH, HEIGHT), BG)
    draw = ImageDraw.Draw(image)
    # Static grid keeps GIF frames compact; only mascot and progress indicators move.
    for x in range(30, WIDTH, 30):
        for y in range(24, HEIGHT, 30):
            draw.point((x, y), fill=(29, 39, 61))
    draw.text((37, 29), "EasyRAG", font=TITLE, fill=(235, 240, 253))
    draw.text((39, 75), "A LITTLE OWL. A WORLD OF KNOWLEDGE.", font=FONTS[10], fill=(112, 133, 162))
    draw.text((347, 39), "从文档，到有依据的答案。", font=FONTS[20], fill=(226, 234, 248))
    draw.text((348, 76), "YOUR KNOWLEDGE, CONNECTED.", font=FONTS[10], fill=CYAN)
    lift = round(4 * math.sin(frame / 64 * math.tau))
    image.paste(mascot, (40, 118 + lift), mascot)
    draw.rounded_rectangle((74, 380, 278, 405), 12, fill=(28, 37, 61), outline=(52, 65, 97))
    draw.text((94, 385), "你的知识，交给聪明搭档。", font=FONTS[12], fill=(159, 175, 203))
    active = min(frame // 16, 3)
    progress = frame % 16 / 15
    for index, (title, sub) in enumerate(STEPS):
        x, y = 348 + index * 153, 130
        current = index == active
        complete = index < active
        outline = CYAN if current else ((65, 103, 105) if complete else (44, 55, 80))
        fill = (23, 48, 54) if current else (20, 29, 49)
        draw.rounded_rectangle((x, y, x + 130, y + 131), 11, fill=fill, outline=outline, width=1)
        draw.text((x + 13, y + 11), f"0{index + 1}", font=FONTS[10], fill=outline)
        if complete:
            draw.line((x + 104, y + 16, x + 107, y + 19, x + 113, y + 12), fill=CYAN, width=2)
        # Small schematic glyphs: file, index, magnifier, answer.
        cx, cy = x + 63, y + 48
        color = CYAN if current or complete else (126, 143, 177)
        if index == 0:
            draw.rounded_rectangle((cx - 10, cy - 10, cx + 9, cy + 13), 3, outline=color, width=2)
            draw.line((cx - 5, cy - 3, cx + 4, cy - 3), fill=color, width=2)
            draw.line((cx - 5, cy + 3, cx + 2, cy + 3), fill=color, width=2)
        elif index == 1:
            for dx, dy in [(-12, -7), (4, -7), (-12, 8), (4, 8)]:
                draw.rounded_rectangle((cx + dx, cy + dy, cx + dx + 9, cy + dy + 9), 2, outline=color)
        elif index == 2:
            draw.ellipse((cx - 12, cy - 11, cx + 5, cy + 6), outline=color, width=2)
            draw.line((cx + 3, cy + 4, cx + 12, cy + 13), fill=color, width=3)
        else:
            draw.rounded_rectangle((cx - 13, cy - 10, cx + 13, cy + 9), 4, outline=color, width=2)
            draw.line((cx - 8, cy + 9, cx - 8, cy + 15, cx - 1, cy + 9), fill=color, width=2)
            for dx in (-6, 0, 6):
                draw.ellipse((cx + dx - 1, cy - 2, cx + dx + 1, cy), fill=color)
        draw.text((x + 29, y + 77), title, font=FONTS[16], fill=(227, 237, 245))
        draw.text((x + 28, y + 105), sub, font=FONTS[10], fill=(132, 151, 177))
        if index < 3:
            line_y = y + 65
            start, end = x + 134, x + 148
            draw.line((start, line_y, end, line_y), fill=(68, 84, 114), width=1)
            draw.line((end - 3, line_y - 3, end, line_y, end - 3, line_y + 3), fill=(68, 84, 114))
            if current:
                dot_x = round(start + (end - start) * progress)
                draw.ellipse((dot_x - 2, line_y - 2, dot_x + 2, line_y + 2), fill=CYAN)
    draw.rounded_rectangle((348, 287, 937, 376), 9, fill=(20, 30, 49), outline=(43, 56, 80))
    draw.text((367, 301), DETAILS[active][0], font=FONTS[14], fill=CYAN)
    draw.text((367, 329), DETAILS[active][1], font=FONTS[13], fill=(160, 178, 203))
    draw.rounded_rectangle((368, 360, 918, 362), 1, fill=(42, 58, 76))
    draw.rounded_rectangle((368, 360, 368 + round(550 * frame / 63), 362), 1, fill=CYAN)
    for index in range(4):
        draw.rounded_rectangle((861 + index * 17, 304, 871 + index * 17, 308), 2,
                               fill=CYAN if index <= active else (55, 67, 93))
    draw.text((349, 392), "流程示意 / 非应用录屏", font=FONTS[10], fill=(91, 111, 143))
    return image


def main():
    frames = [frame_at(index) for index in range(64)]
    # A single stable palette prevents color flicker and improves frame compression.
    atlas = Image.new("RGB", (WIDTH, HEIGHT * 4))
    for index in range(4):
        atlas.paste(frames[index * 16 + 8], (0, HEIGHT * index))
    palette = atlas.quantize(colors=192)
    indexed = [frame.quantize(palette=palette, dither=Image.Dither.NONE) for frame in frames]
    indexed[0].save(ASSETS / "knowledge-flow.gif", save_all=True, append_images=indexed[1:],
                    duration=100, loop=0, optimize=True, disposal=1)
    frame_at(56).save(ASSETS / "overview-poster.png", optimize=True)
    print(f"GIF: {len(frames)} frames, {(ASSETS / 'knowledge-flow.gif').stat().st_size / 1024:.0f} KiB")


if __name__ == "__main__":
    main()
